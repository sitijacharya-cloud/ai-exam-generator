# Data structures

@dataclass
class UnitSpec:
    """A course unit with a name and relative weight/credit hours."""

    name: str
    weight: float


@dataclass
class TypeSpec:
    """Specification for a particular question type in the exam blueprint."""

    qtype: str
    count: int
    difficulty: str
    marks: int


class Question(BaseModel):
    """A single question generated by the LLM."""

    id: str
    unit: str
    type: str
    difficulty: str
    prompt: str
    choices: Optional[List[Dict[str, str]]] = None
    answer: str
    explanation: Optional[str] = None
    marks: Optional[int] = None
    source_ids: List[str]


class ExamPaper(BaseModel):
    """The full exam paper with sections and answer key."""

    title: str
    instructions: str
    sections: Dict[str, List[Question]]
    answer_key: Dict[str, Tuple[str, List[str]]]


