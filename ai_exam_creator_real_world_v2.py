# Document store for RAG

class DocumentStore:


    def __init__(self, persist_dir: str = ".chromadb"):
        self.client = chromadb.PersistentClient(path=persist_dir)
        api_key = os.getenv("OPENAI_API_KEY")
        self.embedding_fn = OpenAIEmbeddingFunction(api_key=api_key, model_name=EMBED_MODEL_NAME)
        self.collection = self.client.get_or_create_collection(
            name="documents", embedding_function=self.embedding_fn
        )
        base_path = os.path.join(os.path.dirname(__file__), "knowledge_base")
        try:
            self._load_initial_documents(base_path)
        except Exception:
            pass

    def _split_text(self, text: str, chunk_size: int = 1000, overlap: int = 200) -> List[str]:
        paragraphs = [p.strip() for p in text.split("\n") if p.strip()]
        chunks: List[str] = []
        current = ""
        for para in paragraphs:
            if len(current) + len(para) <= chunk_size:
                current += para + " "
            else:
                chunks.append(current.strip())
                current = para + " "
        if current.strip():
            chunks.append(current.strip())
        return chunks

    def add_document(self, name: str, text: str, source_type: str = "user") -> int:
        chunks = self._split_text(text)
        ids = [f"{name}_chunk_{i}" for i in range(len(chunks))]
        metadatas = [
            {"source": name, "chunk_index": i, "source_type": source_type}
            for i in range(len(chunks))
        ]
        try:
            existing_ids = [doc_id for doc_id in ids if doc_id in self.collection.get()["ids"]]
            if existing_ids:
                self.collection.delete(ids=existing_ids)
        except Exception:
            pass
        self.collection.add(documents=chunks, ids=ids, metadatas=metadatas)
        return len(chunks)

    def _document_present(self, name: str) -> bool:
        try:
            ids = self.collection.get()["ids"]
        except Exception:
            ids = []
        prefix = f"{name}_chunk_"
        return any(doc_id.startswith(prefix) for doc_id in ids)

    def _load_initial_documents(self, base_path: str) -> None:
        if not os.path.isdir(base_path):
            return
        for file_name in os.listdir(base_path):
            if not file_name.lower().endswith(".pdf"):
                continue
            name = file_name
            if self._document_present(name):
                continue
            file_path = os.path.join(base_path, file_name)
            try:
                with open(file_path, "rb") as f:
                    pdf_bytes = f.read()
                from io import BytesIO
                text = pdfminer.high_level.extract_text(BytesIO(pdf_bytes)) or ""
                if text.strip():
                    self.add_document(name, text, source_type="knowledge_base")
            except Exception:
                continue

    def query(
        self,
        query: str,
        top_k: int = 3,
        source_types: Optional[List[str]] = None,
    ) -> List[Tuple[str, str]]:
        
        result = self.collection.query(
            query_texts=[query],
            n_results=top_k * 5,
            include=["documents", "metadatas", "distances"],
        )
        documents = result.get("documents", [[]])[0]
        ids = result.get("ids", [[]])[0]
        metadatas = result.get("metadatas", [[]])[0]
        matches: List[Tuple[str, str]] = []
        for doc_text, doc_id, meta in zip(documents, ids, metadatas):
            if source_types is None or meta.get("source_type") in source_types:
                matches.append((doc_text, doc_id))
                if len(matches) >= top_k:
                    break
        return matches

    def get_texts_by_ids(self, ids: List[str]) -> List[str]:
        if not ids:
            return []
        try:
            result = self.collection.get(ids=ids, include=["documents"])
            texts = []
            for doc_list in result.get("documents", []):
                if doc_list:
                    texts.append(doc_list[0])
            return texts
        except Exception:
            return ["<unavailable>"] * len(ids)


